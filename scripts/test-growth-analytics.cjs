const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const file = path.resolve('client/src/lib/growthAnalytics.ts');
const storage = new Map();
global.sessionStorage = { getItem: k => storage.get(k) ?? null, setItem: (k,v) => storage.set(k,v), removeItem: k => storage.delete(k) };
global.window = { location: { search: '?utm_source=club&utm_campaign=fall' } };
let requests = [];
const mod = new Module(file, module);
mod.filename = file;
mod.require = name => name === '@/lib/apiClient' ? { apiFetch: async (...args) => { requests.push(args); return { ok: true }; } } : require(name);
mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, file);
const { growthAttribution, trackGrowth } = mod.exports;
const a = growthAttribution();
assert.equal(a.source, 'club');
assert.equal(a.campaign, 'fall');
assert.equal(growthAttribution().journeyId, a.journeyId);
trackGrowth('Event Viewed', 'event');
trackGrowth('Event Viewed', 'event');
assert.equal(requests.length, 1);
assert.equal(requests[0][1].skipAuth, true);
assert.equal(requests[0][1].body.journeyId, a.journeyId);
assert.equal(requests[0][1].body.viewerUserId, undefined);
const old = JSON.parse(storage.get('cl-growth-journey-v1'));
old.updatedAt = Date.now() - 31 * 60000;
storage.set('cl-growth-journey-v1', JSON.stringify(old));
window.location.search = '';
const next = growthAttribution();
assert.notEqual(next.journeyId, a.journeyId);
assert.equal(next.source, undefined);
global.sessionStorage = { getItem() { throw new Error('blocked'); } };
assert.equal(growthAttribution(), undefined);
assert.doesNotThrow(() => trackGrowth('Registration Started','event'));
console.log('PASS attribution continuity, expiry, deduplication, anonymous telemetry and blocked-storage safety');
